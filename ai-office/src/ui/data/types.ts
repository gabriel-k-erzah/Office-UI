// Shapes for the dashboard's live state. Everything starts empty: there's no
// project until one is created.

export type TaskStatus = "todo" | "inProgress" | "review" | "done";
export type TaskPriority = "high" | "medium" | "low";

export type Task = {
  id: string;
  title: string;
  assigneeId: string;
  status: TaskStatus;
  priority: TaskPriority;
  due: string;
  // From the manager's plan: what good looks like, and whether to file the result.
  brief?: string;
  document?: boolean;
  planId?: string;
  // The agent's notes once it's done.
  result?: string;
};

export type ChatMessage = {
  id: string;
  authorId: string | "user";
  time: string;
  text: string;
  // Set on replies generated by a model.
  model?: string;
  error?: boolean;
  // Lounge small talk between agents rather than work.
  casual?: boolean;
};

export type ActivityItem = {
  id: string;
  agentId: string;
  text: string;
  ago: string;
};

export type LogKind = "tool" | "thinking" | "system" | "error";

export type LogEntry = {
  id: string;
  time: string;
  agentId: string | "system";
  kind: LogKind;
  text: string;
};

export const isActive = (task: Task) => task.status !== "done";
